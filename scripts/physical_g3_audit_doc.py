"""Write docs/PERTURBATION_PHYSICS_AUDIT.md from the Gate 3/4/5 result tables.

All numbers come from the CSVs; rerun after any new paired case is processed.
"""
import os
import re

import pandas as pd

R = os.path.join(os.path.dirname(__file__), "..")
S = pd.read_csv(os.path.join(R, "results/tables/physical_g3_summary.csv"))
X = pd.read_csv(os.path.join(R, "results/tables/physical_g5_exclusion.csv"))
C = pd.read_csv(os.path.join(R, "results/physical_model_vs_prescribed_patch.csv"))
P = pd.read_csv(os.path.join(R, "results/tables/physical_prediction_outcomes.csv"))


def g(x, f="{:.3g}"):
    return "—" if pd.isna(x) else f.format(x)


def esc(s):
    return re.sub(r"\|([^|]+)\|", r"abs(\1)", s).replace("|", "\\|")


def table(df, cols):
    cols = [(esc(h), c, f) for h, c, f in cols]
    out = ["| " + " | ".join(h for h, _, _ in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(esc(fn(r[c]) if fn else str(r[c])) for _, c, fn in cols) + " |")
    return "\n".join(out)


pct = lambda x: g(100 * x, "{:+.3g} %")  # noqa: E731
hrs = lambda x: g(x / 3600, "{:.2f}")  # noqa: E731
num = lambda x: g(x)  # noqa: E731

CASE_COLS = ["label", "P0_W", "z0_km", "sigma_h_km", "duration_s", "E_total_J",
             "closure_first_snapshot", "closure_end_heating", "closure_final", "t_end_s"]
cases = S.drop_duplicates("label")[CASE_COLS]
L = ["# Gate 3 — Perturbation physics audit (GITM paired runs)", "",
     "Generated by `scripts/physical_g3_audit_doc.py` from",
     "`results/tables/physical_g3_summary.csv`, `results/tables/physical_g5_exclusion.csv`,",
     "`results/physical_model_vs_prescribed_patch.csv` and `results/tables/physical_prediction_outcomes.csv`.",
     "Every perturbed case is differenced against a control restarted from the same spin-up with identical",
     "inputs, ranks and output cadence; the control-vs-control noise floor is 4.8e-6 relative density (V10).",
     "", "## 1. Cases and energy closure (V8/V9)", "",
     "Closure = Δ(∫ρ c_p T dV)(perturbed − control) / ∫P dt. The first-snapshot value tests V9 (within 20 %);",
     "later values fall as energy is conducted downward, radiated (NO/CO2) and converted to winds/potential energy.",
     "", table(cases, [("case", "label", None), ("P0 [W]", "P0_W", num), ("z0 [km]", "z0_km", num),
                       ("σh [km]", "sigma_h_km", num), ("heating [h]", "duration_s", hrs),
                       ("E [J]", "E_total_J", num), ("closure first", "closure_first_snapshot", num),
                       ("end of heating", "closure_end_heating", num), ("end of run", "closure_final", num),
                       ("run [h]", "t_end_s", hrs)]),
     "", "## 2. Neutral density, temperature, winds and composition", "",
     table(S, [("case", "label", None), ("alt", "alt_km", num), ("peak δρ/ρ", "peak_drho_rel", pct),
               ("t_peak−t_on [h]", "t_peak_after_onset_s", hrs), ("peak dist [km]", "dist_of_peak_km", num),
               ("min δρ/ρ", "min_drho_rel", pct), ("max ΔT [K]", "max_dT_K", num),
               ("max |Δv_h| [m/s]", "max_dvh_ms", num), ("max |Δv_up| [m/s]", "max_abs_dvu_ms", num),
               ("min Δ(O/N2)", "min_dOn2_rel", pct), ("max Δ(O/N2)", "max_dOn2_rel", pct)]),
     "", "## 3. Spread, remote response, sign changes and persistence", "",
     "Area fractions are of the global sphere at that altitude; remote = beyond 3000 km great-circle distance",
     "from the source centre; e-folding times are measured after heating switch-off.", "",
     table(S, [("case", "label", None), ("alt", "alt_km", num),
               ("max area |δ|>1 %", "max_area_frac_gt_1pct", pct),
               ("final area |δ|>1 %", "final_area_frac_gt_1pct", pct),
               ("max area δ<−0.1 %", "max_area_frac_neg", pct), ("max remote |δ|", "max_remote_abs_drho_rel", pct),
               ("max global-mean δ", "max_global_mean_drho_rel", pct),
               ("final global-mean δ", "final_global_mean_drho_rel", pct),
               ("e-fold local peak [h]", "efold_peak_after_off_s", hrs),
               ("e-fold global mean [h]", "efold_globalmean_after_off_s", hrs)]),
     "", "## 4. Orbit coupling and selectivity (Gate 4)", "",
     "256 synthetic circular objects per altitude, B = 30 kg m⁻², 12 h; \"target\" = objects whose ground",
     "track passes within σh of the source centre during heating. Prescribed = static Gaussian fitted to the",
     "GITM peak δ, width and window (the baseline's representation). Sensitivity columns: no winds, nearest-",
     "neighbour interpolation, altitude referenced to 6378 km, 1200-s output sampling.", ""]
t = C[C.group != "all"].pivot_table(index=["label", "alt_km"], columns="group",
                                    values=["gitm_extra_dv_mean", "prescribed_extra_dv_mean"]).reset_index()
t.columns = ["label", "alt_km", "g_non", "g_tgt", "p_non", "p_tgt"]
t["sel_g"] = t.g_tgt / t.g_non
t["sel_p"] = t.p_tgt / t.p_non
tg = C[C.group == "target"].set_index(["label", "alt_km"])
for k, c in [("nw", "gitm_extra_dv_mean_no_winds"), ("nn", "gitm_extra_dv_mean_nearest_interp"),
             ("re", "gitm_extra_dv_mean_alt_ref_6378km"), ("dt", "gitm_extra_dv_mean_dt_1200s")]:
    t[k] = [tg.loc[(a, b), c] / tg.loc[(a, b), "gitm_extra_dv_mean"] - 1 for a, b in zip(t.label, t.alt_km)]
t["nat"] = [tg.loc[(a, b), "natural_dv_12h_mean"] for a, b in zip(t.label, t.alt_km)]
t["fitlat"] = [tg.loc[(a, b), "fit_lat"] for a, b in zip(t.label, t.alt_km)]
t["tgt_nat"] = t.g_tgt / t.nat
L += [table(t, [("case", "label", None), ("alt", "alt_km", num), ("target Δv [m/s]", "g_tgt", num),
                ("target/natural", "tgt_nat", pct), ("sel. GITM", "sel_g", num), ("sel. prescribed", "sel_p", num),
                ("no winds", "nw", pct), ("nearest", "nn", pct), ("r_ref 6378", "re", pct), ("Δt 1200 s", "dt", pct),
                ("fit lat", "fitlat", num)])]
L += ["", "Selectivity = mean target / mean non-target extra Δv. The fitted prescribed patch is centred on the",
      "GITM grid maximum at that altitude; where the fitted latitude departs from the 45° source latitude the",
      "comparator is less representative.", "",
      "## 5. Energy-anchored efficiency (Gate 5 input)", "",
      table(X, [("case", "label", None), ("alt", "alt_km", num), ("E [J]", "E_input_J", num),
                ("target Δv @B_ref [m/s]", "target_dv_ms_at_Bref", num),
                ("non-target share of extra drag", "nontarget_share_of_extra_drag", pct),
                ("target Δv per J", "target_dv_per_J", num),
                ("linear power for baseline tracking Δv in 1 d [W]", "equiv_continuous_power_1day_W_linear", num)]),
      "", "The last column linearly extrapolates far outside the simulated regime and, given the sublinear",
      "peak response (PR2), is a lower bound on the required power only if Δv per joule does not fall further.",
      "", "## 6. Frozen-prediction scoring", "",
      table(P, [("ID", "prediction", None), ("quantity", "quantity", None), ("value", "value", num),
                ("verdict", "verdict", None), ("note", "note", lambda x: "" if pd.isna(x) else str(x))]), ""]
open(os.path.join(R, "docs/PERTURBATION_PHYSICS_AUDIT.md"), "w").write("\n".join(L))
print("wrote docs/PERTURBATION_PHYSICS_AUDIT.md")
